/**
 * Available chat folders in the top tab strip.
 */
enum class ChatFolder(val title: String) {
    ALL("All"),
    PERSONAL("Personal"),
    WORK("Work"),
    CHANNELS("Channels")
}

/**
 * Storage bucket of a chat item; VAULT chats remain hidden from search and main lists while locked.
 */
enum class ChatLocation {
    MAIN,
    ARCHIVE,
    VAULT
}

/**
 * Represents a chat row in the Telegram list demo.
 */
data class ChatItem(
    val id: Long,
    val title: String,
    val senderPrefix: String? = null,
    var lastMessage: String,
    val time: String,
    var unreadCount: Int,
    var isMuted: Boolean,
    var isPinned: Boolean,
    var isOutgoingRead: Boolean,
    val isPremium: Boolean = false,
    val isVerified: Boolean = false,
    val statusEmoji: String? = null,
    val avatarColors: Pair<Int, Int>,
    val initials: String,
    val avatarGlyph: AvatarGlyph = AvatarGlyph.INITIALS,
    val avatarResId: Int? = null,
    val folders: Set<ChatFolder>,
    var location: ChatLocation
)

